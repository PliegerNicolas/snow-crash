    croned_exploit_path="/opt/openarenaserver/exploit.sh";
    checkflag_capture_path="/tmp/checkflag"; # Generated by the injected 'exploit.sh' script.

    # exploit_cron_script_path="/opt/openarenaserver/getflag.sh";
    # checkflag_output_path="/tmp/checkflag";
